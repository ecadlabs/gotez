package proto_023_PtSeouLo

import (
	"testing"

	"github.com/ecadlabs/gotez/v2"
	"github.com/ecadlabs/gotez/v2/encoding"
	"github.com/ecadlabs/gotez/v2/protocol/core"
	"github.com/ecadlabs/gotez/v2/protocol/core/expression"
	"github.com/stretchr/testify/require"
)

func TestPack(t *testing.T) {
	src := []byte{0x05, 0x0a, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x32, 0x04, 0x1d, 0xca, 0x76, 0xba, 0xc9, 0x40, 0xb4, 0x78, 0xaa, 0xe6, 0x73, 0xe3, 0x62, 0xbd, 0x15, 0x84, 0x7e, 0xd8}
	var out SignRequest
	_, err := encoding.Decode(src, &out)
	require.NoError(t, err)
	expect := core.PackData{
		Expression: expression.Bytes{
			Bytes: gotez.Bytes{0x0, 0x0, 0x32, 0x4, 0x1d, 0xca, 0x76, 0xba, 0xc9, 0x40, 0xb4, 0x78, 0xaa, 0xe6, 0x73, 0xe3, 0x62, 0xbd, 0x15, 0x84, 0x7e, 0xd8},
		},
	}
	require.Equal(t, expect, out)
}
