package rlp

import (
	"math/big"
	"testing"

	"github.com/stretchr/testify/require"
)

func mustInt(s string) *big.Int {
	res, ok := new(big.Int).SetString(s, 10)
	if !ok {
		panic("parsing error")
	}
	return res
}

func TestBigInt(t *testing.T) {
	cases := []struct {
		val    *big.Int
		binary []byte
	}{
		{
			val:    big.NewInt(0),
			binary: []byte{0},
		},
		{
			val:    big.NewInt(1),
			binary: []byte{1},
		},
		{
			val:    mustInt("123456789"),
			binary: []byte{0x84, 0x7, 0x5b, 0xcd, 0x15},
		},
		{
			val:    mustInt("115792089210356248762697446949407573530086143415290314195533631308867097853951"),
			binary: []byte{0xa0, 0xff, 0xff, 0xff, 0xff, 0x0, 0x0, 0x0, 0x1, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff},
		},
		{
			val:    mustInt("6864797660130609714981900799081393217269435300143305409394463459185543183397656052122559640661454554977296311391480858037121987999716643812574028291115057151"),
			binary: []byte{0xb8, 0x42, 0x1, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff},
		},
	}

	for _, c := range cases {
		var b Builder
		b.AddBigInt(c.val)
		bin, err := b.Bytes()
		require.NoError(t, err)
		require.Equal(t, c.binary, bin)

		s := Stream(bin)
		res, err := s.BigInt()
		require.NoError(t, err)
		require.Equal(t, 0, res.Cmp(c.val))
	}
}

